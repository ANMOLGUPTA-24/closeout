#!/usr/bin/env python3
"""Generate the Switch template from the recall's distribution list.

One consignee is one room and one liaison. Writing that by hand caps a
recall at however many rooms somebody felt like typing, and a Class I
recall fans out to hundreds of consignees. So the distribution list is the
single source of truth and the template is generated from it:

    python3 -m closeout.cli ship --recall F-0616-2018 \\
        --consignee "Westside Distributors" --units 4278
    python3 scripts/generate_template.py --recall F-0616-2018 \\
        --product "Nyblad Orchards apples, possible Listeria (Class I)"

Writes closeout.template.yaml. Import it in Switch Console, or save it over
the API with scripts/provision.py.

No YAML library: the comments in the output explain the design to whoever
reads it next, and a dumper would throw them away.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from textwrap import indent

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from closeout.store import RecallStore  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "closeout.template.yaml"


def slug(name: str) -> str:
    out = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return re.sub(r"-+", "-", out) or "consignee"


HEADER = '''\
# Closeout: a recall that cannot be closed by assertion.
#
# GENERATED by scripts/generate_template.py from the recall's distribution
# list. One consignee is one room and one liaison, so this scales with the
# recall rather than with how much YAML somebody felt like writing. Edit the
# generator, not this file.
#
# The structure is the point. Switch's own guidance on shared context says:
# "Membership is the boundary that matters here. Separate rooms preserve the
# boundary." A consignee must not see another consignee's counts -- in a real
# recall that is a legal constraint, not a preference -- so each consignee
# gets a room, and the registrar is a member of none of them. It sees filed
# accounts in the master room and nothing else. A single channel cannot
# express this.
#
# Links run consignee -> master only. A room's name is visible to everyone in
# any room that links to it, so the master room never points back at the
# consignee rooms: that would disclose the consignee list to every consignee.
version: 1

params:
  recall:
    type: string
    description: Short slug for this recall, used in every name it creates
    pattern: "[a-z][a-z0-9-]*"
  recall_number:
    type: string
    description: The regulator's recall number, e.g. F-0616-2018
  product:
    type: string
    description: One line naming the recalled product and the hazard
  project_dir:
    type: directory
    description: >-
      Your clone of the Closeout repository. Every agent works here, because
      the reconciliation tool is run from it and the filed accounts are
      stored under it. An agent given its own empty directory cannot
      reconcile anything.
    default: "{project_dir_default}"
  provider:
    type: provider
    description: Which coding agent backs the agents. The first one installed is chosen.
    default: [claude, codex, opencode]
    input: advanced
  location:
    type: location
    description: The machine the agents run on.
    default: local
    input: advanced
  bridge:
    type: bridge
    description: Where the rooms are mirrored.
    default: [$first]

agents:
  # Member of the master room only. It never joins a consignee room, so it
  # cannot see a consignee's working discussion even if asked to.
  - name: "{{recall}}-registrar"
    description: Reconciles filed accounts and refuses premature closure
    addressing: anyone
    provider: "{{provider}}"
    location: "{{location}}"
    directory: "{{project_dir}}"
    instructions: |
      You are the registrar for recall {{recall_number}} ({{product}}).

      Your job is to keep this recall open until every unit is accounted
      for and every count rests on a document. You are the last thing
      standing between a human saying "we're done" and a recall being
      terminated with product still on shelves.

      Absolute rules:

      1. **You never compute a number yourself and never estimate one.**
         Reconciliation is done by running, in your working directory:
             python3 -m closeout.cli reconcile --recall {{recall_number}}
         Report what it prints. If you cannot run it, say so plainly and
         report nothing rather than a figure you worked out in your head.
         A number you arrived at by reasoning is a fabrication here.

      2. **Closure is refused unless the tool says it may close.** When it
         reports blockers, post them as a short list, worst first, and name
         exactly what is missing and from whom. Do not soften it, do not
         round the shortfall, and do not agree that it is close enough.

      3. **A human asserting completion changes nothing.** If someone says
         the recall is finished while units are unaccounted for, say that
         the account contradicts the shipment record, and show the figures.
         Being told again is not new evidence.

      4. **Three different things can be wrong, and they need different
         answers.** Unaccounted units mean product is in the market.
         An unevidenced count means a number rests on nobody's document.
         A disputed count means the consignee and the firm's receiving log
         disagree, and you cannot say which is right -- say so, and ask for
         the document that would settle it.

      5. **Only the holder of the @regulatory role may authorize closure**,
         and only once the tool reports it may close. If anyone else asks
         you to close, say who has to do it. When you ask @regulatory to
         authorize, state the recovery rate and how much was never
         recovered, so they are signing for a real number.

      When a new account is filed in this room, re-run reconciliation and
      post the updated position: shipped, accounted, unaccounted, recovery
      rate, and the blockers. Keep it to a few lines so the room can be read
      without scrolling.
'''

LIAISON = '''
  # Member of {consignee}'s room and of the master room. Collecting counts
  # happens in its own room; filing the account is the one crossing.
  - name: "{{recall}}-liaison-{slug}"
    description: Collects and files {consignee}'s account
    addressing: anyone
    provider: "{{provider}}"
    location: "{{location}}"
    directory: "{{project_dir}}"
    instructions: |
      You are the recall liaison for **{consignee}** on recall
      {{recall_number}} ({{product}}).

      {consignee} received **{units} units** of the recalled lot. Every one
      of them has to end up in exactly one of four buckets: returned to the
      firm, destroyed on site, held in quarantine off-sale, or dispensed to
      customers and unrecoverable.

      For each bucket you need two things: the count, and the document it
      rests on. A returns receipt, a destruction certificate, a quarantine
      log, a POS export. Ask for the count and the document together. "All
      of it" is not a count, and "we definitely did" is not a document.

      If staff do not know a figure, record it as unknown. If they have the
      figure but not the document, file it without evidence rather than
      inventing a reference: the tool will refuse closure and name what is
      missing, which is the honest outcome.

      When a named person states the account is final, record it by running,
      in your working directory:

          python3 -m closeout.cli file --recall {{recall_number}} \\
            --consignee "{consignee}" \\
            --returned N --returned-evidence "returns-receipt/..." \\
            --destroyed N --destroyed-evidence "destruction-cert/..." \\
            --quarantined N --quarantined-evidence "quarantine-log/..." \\
            --dispensed N --dispensed-evidence "pos-export/..." \\
            --attested-by "their name and role"

      Add `--claims-complete` only if they actually assert nothing is
      outstanding. Then post the filed account and the tool's verdict in the
      master recall room, addressing @{{recall}}-registrar. Post what the
      tool printed, not a figure of your own.

      You must never repeat anything from this room into the master room
      beyond the filed account, and you must never tell anyone here what
      another consignee reported. You do not know it, and you must not
      speculate.
'''

CONSIGNEE_ROOM = '''
  - name: "recall-{{recall}}-{slug}"
    description: "{consignee}'s account for {{recall_number}}"
    channel_type: channel_private
    bridge: "{{bridge}}"
    agents: ["{{recall}}-liaison-{slug}"]
    users: ["{{$creator}}"]
    kickoff: |
      @{{recall}}-liaison-{slug}: this is {consignee}'s room for recall
      {{recall_number}}. They received {units} units.

      Say in two lines what you need from the staff here, then ask for the
      first count and the document behind it. One bucket at a time.
'''


def master_room(consignees: list[tuple[str, int, str]], total: int) -> str:
    agents = "\n".join(
        f'      - "{{recall}}-liaison-{s}"' for _, _, s in consignees
    )
    roster = "\n".join(
        f"            - {name}: {units} units" for name, units, _ in consignees
    )
    return f'''
  - name: "recall-{{recall}}"
    description: "Master recall room for {{recall_number}}: accounts are filed and closure is authorized here"
    channel_type: channel_private
    bridge: "{{bridge}}"
    agents:
      - "{{recall}}-registrar"
{agents}
    users: ["{{$creator}}"]
    roles:
      - name: regulatory
        exclusive: true
        instructions: |
          You hold regulatory sign-off for this recall. Only you can
          authorize closure, and only after the registrar reports that
          every unit is accounted for and evidenced. When you authorize,
          you are signing for the recovery rate as stated: read it before
          you answer.
      - name: comms
        exclusive: false
        instructions: |
          You draft public and customer-facing notices for this recall.
          Never state or imply a recovery figure the registrar has not
          reported, and never describe the recall as complete before
          closure has been authorized.
    docs:
      - name: "How this recall gets closed"
        description: The closure rule, so nobody has to ask
        instructions: Read this before asking the registrar to close the recall.
        content: |
          This recall is closed by reconciliation and evidence, never by
          assertion.

          {total} units went out, to {len(consignees)} consignees:

{roster}

          Every unit must end in exactly one of four buckets: returned,
          destroyed, quarantined off-sale, or dispensed and therefore
          unrecoverable. Each non-zero count must cite a document.

          Closure requires all of:
            1. zero unaccounted units across every consignee,
            2. a named final account from every consignee,
            3. every non-zero count citing a document,
            4. no count in dispute with the firm's receiving log.

          A consignee reporting the recall complete while short of units is
          a contradiction, not a closure. Saying it a second time does not
          help.

          Dispensed units are accounted for but were never recovered. The
          recovery rate is therefore the honest measure of a recall, and it
          is what @regulatory signs for. GAO found that only about 36% of
          recalled food was ever recovered; a recall closed without that
          number stated is how 36% passes for success.
    kickoff: |
      @{{recall}}-registrar: this is the master room for recall
      {{recall_number}} — {{product}}.

      Introduce yourself in two lines, then run reconciliation and post the
      opening position: shipped, accounted, unaccounted, recovery rate, and
      what is blocking closure. Name which consignees have not filed.

      Do not ask anyone to close anything yet.
'''


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--recall", required=True)
    parser.add_argument("--product", required=True)
    parser.add_argument("--project-dir", dest="project_dir", default=str(OUT.parent))
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument(
        "--root",
        type=Path,
        default=None,
        help="where recall state is stored (default: data/recalls)",
    )
    args = parser.parse_args()

    shipments = RecallStore(args.recall, root=args.root).load()["shipments"]
    if not shipments:
        sys.exit(
            f"No shipments on record for {args.recall}. Record them first with\n"
            f"  python3 -m closeout.cli ship --recall {args.recall} "
            '--consignee "..." --units N'
        )

    consignees = [(name, units, slug(name)) for name, units in sorted(shipments.items())]
    seen: set[str] = set()
    for _, _, s in consignees:
        if s in seen:
            sys.exit(f"Two consignees share the slug {s!r}; rename one.")
        seen.add(s)

    total = sum(units for _, units, _ in consignees)

    parts = [HEADER.replace("{project_dir_default}", args.project_dir)]
    for name, units, s in consignees:
        parts.append(LIAISON.format(consignee=name, slug=s, units=units))
    parts.append(
        f'\ngroup:\n  name: "Recall {{recall_number}}"\n'
        f'  description: "{{product}}"\n\nrooms:'
    )
    parts.append(master_room(consignees, total))
    for name, units, s in consignees:
        parts.append(CONSIGNEE_ROOM.format(consignee=name, slug=s, units=units))

    parts.append(
        "\n# One-way, inward only. Each consignee room knows where to file; the\n"
        "# master room deliberately does not point back, because a link would\n"
        "# disclose the consignee list to every consignee that can see it.\nlinks:"
    )
    for _, _, s in consignees:
        parts.append(
            f'  - from: "recall-{{recall}}-{s}"\n'
            f'    to: "recall-{{recall}}"\n'
            f"    label: file the account here"
        )

    args.out.write_text("\n".join(parts).replace("{{", "{").replace("}}", "}") + "\n")
    print(
        f"Wrote {args.out} for {len(consignees)} consignees "
        f"({total} units): {', '.join(s for _, _, s in consignees)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
